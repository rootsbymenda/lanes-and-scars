    def run_ctm(self, *argv):
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            try:
                rc = ctm.main([str(a) for a in argv])
            except SystemExit as exc:
                rc = exc.code
        return rc, out.getvalue(), err.getvalue()

    def index(self, *extra):
        rc, out, err = self.run_ctm("index", "--claude-dir", self.cdir, "--db", self.db, "-q", *extra)
        self.assertEqual(rc, 0, err)
        return self.meta("last_run")

    def meta(self, key):
        con = sqlite3.connect(self.db)
        try:
            return json.loads(con.execute("SELECT value FROM meta WHERE key=?", (key,)).fetchone()[0])
        finally:
            con.close()

    def find(self, *args):
        rc, out, err = self.run_ctm("find", "--db", self.db, *args)
        self.assertEqual(rc, 0, err)
        return out

    @staticmethod
    def addresses(out):
        return [(m.group(1), int(m.group(2))) for m in re.finditer(r"^    ((?:/|[A-Za-z]:\\).*):(\d+)$", out, re.M)]

    @staticmethod
    def headers(out):
        return re.findall(r"^\[\d+\] .*$", out, re.M)


