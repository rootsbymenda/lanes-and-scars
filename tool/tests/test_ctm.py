def ts(y, mo, d, h=12, mi=0, s=0):
    return dt.datetime(y, mo, d, h, mi, s, tzinfo=UTC).strftime("%Y-%m-%dT%H:%M:%S.000Z")


def epoch_ms(y, mo, d, h=12, mi=0):
    return int(dt.datetime(y, mo, d, h, mi, tzinfo=UTC).timestamp() * 1000)


def msg(kind, content, when, session=S1, **extra):
    record = {"type": kind, "timestamp": when, "sessionId": session, "message": {"role": kind, "content": content}}
    record.update(extra)
    return record


def jsonl(records):
    return "".join((r if isinstance(r, str) else json.dumps(r)) + "\n" for r in records)


def write(path, text, mode="w"):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, mode, encoding="utf-8", newline="") as f:
        f.write(text)


def nth_line(path, n):
    with open(path, "rb") as f:
        for number, raw in enumerate(f, 1):
            if number == n:
                return raw.decode("utf-8", "replace")
    return None


def bump_mtime(path, seconds=10):
    st = os.stat(path)
    os.utime(path, ns=(st.st_atime_ns, st.st_mtime_ns + seconds * 10 ** 9))


