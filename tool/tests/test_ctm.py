class ExtractionTest(unittest.TestCase):
    def src(self, sub=False):
        return ctm.Source("transcripts", "/x/s.jsonl", project=APP, session=S1, sub=sub)

    def roles(self, record, sub=False):
        return [(r, k) for r, k, _ in ctm.extract_transcript(record, self.src(sub))[3]]

    def test_who_wrote_it(self):
        when = ts(2026, 1, 1)
        self.assertEqual(self.roles(msg("user", "hi", when, **HUMAN)), [("user", "prompt")])
        self.assertEqual(self.roles(msg("user", "hi", when)), [("user", "prompt")])
        self.assertEqual(self.roles(msg("user", "hi", when, isMeta=True)), [("system", "meta")])
        self.assertEqual(self.roles(msg("user", "hi", when, origin={"kind": "peer"}, isMeta=True)),
                         [("assistant", "peer-message")])
        self.assertEqual(self.roles(msg("user", "hi", when, turnOrigin="sdk")), [("system", "sdk")])
        self.assertEqual(self.roles(msg("user", "hi", when), sub=True), [("assistant", "agent-prompt")])
        self.assertEqual(self.roles(msg("user", "hi", when, isSidechain=True)), [("assistant", "agent-prompt")])
        self.assertEqual(self.roles(msg("user", "hi", when, isCompactSummary=True)), [("system", "compact-summary")])
        self.assertEqual(self.roles(msg("assistant", [{"type": "text", "text": "ok"}], when), sub=True),
                         [("assistant", "agent-text")])
        note = {"type": "attachment", "timestamp": when, "attachment": {
            "type": "queued_command", "prompt": "job done", "commandMode": "task-notification"}}
        self.assertEqual(self.roles(note), [("system", "task-notification")])
        ignored = {"type": "attachment", "attachment": {"type": "nested_memory", "content": "copied context"}}
        self.assertEqual(self.roles(ignored), [])

    def test_tool_input_keeps_words_whole(self):
        record = msg("assistant", [{"type": "tool_use", "name": "Bash",
                                    "input": {"command": 'echo "hi"\nls -la', "flags": [1, {"deep": "value"}]}}],
                     ts(2026, 1, 1))
        text = ctm.extract_transcript(record, self.src())[3][0][2]
        self.assertEqual(text, 'Bash\ncommand: echo "hi"\nls -la\nflags: 1\nflags.deep: value')

    def test_history_line(self):
        record = {"display": "hello", "timestamp": epoch_ms(2026, 3, 4, 5, 6), "project": "/work/demo/my_app",
                  "pastedContents": {"1": {"type": "text", "contentHash": "abc"}, "2": {"type": "text", "content": "pasted"}}}
        when, session, project, rows = ctm.extract_history(record, ctm.Source("history", "/x/h.jsonl"))
        self.assertEqual((when, session, project), ("2026-03-04T05:06:00Z", None, "-work-demo-my-app"))
        self.assertEqual(rows, [("user", "prompt", "hello"), ("user", "paste", "pasted")])

    def test_timestamps(self):
        self.assertEqual(ctm.norm_ts("2026-01-15T10:00:00.123Z"), "2026-01-15T10:00:00Z")
        self.assertEqual(ctm.norm_ts("2026-01-15T10:00:00+02:00"), "2026-01-15T08:00:00Z")
        self.assertEqual(ctm.norm_ts(epoch_ms(2026, 1, 15, 10, 0)), "2026-01-15T10:00:00Z")
        self.assertEqual(ctm.norm_ts(epoch_ms(2026, 1, 15, 10, 0) // 1000), "2026-01-15T10:00:00Z")
        for junk in ("yesterday", None, True, {}, "2026-13-45T10:00:00Z"):
            self.assertIsNone(ctm.norm_ts(junk))

    def test_query_building(self):
        self.assertEqual(ctm.build_match('fix "login form" valid*', False),
                         ('"fix" AND "login form" AND "valid"*', ["fix", "login form", "valid"]))
        self.assertEqual(ctm.build_match('say "hi"there', False)[0], '"say" AND "hi" AND "there"')

    def test_chunks_keep_line_numbers(self):
        text = "\n\n# A\none\n\n## B\ntwo\nthree\n"
        pieces = list(ctm._chunks(io.StringIO(text)))
        self.assertEqual([start for start, _ in pieces], [3, 6])
        self.assertEqual(ctm._locate(pieces[1][1], pieces[1][0], ["three"]), 8)

    def test_slug(self):
        self.assertEqual(ctm.slugify("/work/demo/my_app.v2"), "-work-demo-my-app-v2")


@unittest.skipIf(sys.platform == "win32", "uses the resource module")
class StreamingTest(unittest.TestCase):
    CHILD = ("import resource, sys\n"
             "sys.path.insert(0, sys.argv[1])\n"
             "import ctm\n"
             "rc = ctm.main(['index', '--claude-dir', sys.argv[2], '--db', sys.argv[3], '-q'])\n"
             "peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss\n"
             "print(rc, peak // 1024 if sys.platform == 'darwin' else peak)\n")

    def peak_kib(self, cdir, db):
        res = subprocess.run([sys.executable, "-c", self.CHILD, ROOT, cdir, db],
                             capture_output=True, text=True, timeout=900)
        self.assertEqual(res.returncode, 0, res.stderr)
        rc, peak = res.stdout.split()
        self.assertEqual(rc, "0")
        return int(peak)

    def test_50mb_transcript_is_streamed(self):
        with tempfile.TemporaryDirectory() as tmp:
            small = os.path.join(tmp, "small")
            write(os.path.join(small, "projects", APP, S1 + ".jsonl"), jsonl([msg("user", "hello", ts(2026, 1, 1))]))
            big = os.path.join(tmp, "big")
            path = os.path.join(big, "projects", APP, S1 + ".jsonl")
            os.makedirs(os.path.dirname(path))
            block = "lorem ipsum dolor sit amet " * 2000
            with open(path, "w", encoding="utf-8") as f:
                for i in range(1000):
                    content = [{"type": "tool_result", "tool_use_id": "t", "content": f"chunkmarker{i} {block}"}]
                    f.write(json.dumps(msg("user", content, ts(2026, 1, 1))) + "\n")
            size = os.path.getsize(path)
            self.assertGreaterEqual(size, 50 * MIB)
            base = self.peak_kib(small, os.path.join(tmp, "small.db"))
            peak = self.peak_kib(big, os.path.join(tmp, "big.db"))
            growth = (peak - base) * 1024
            self.assertLess(growth, size / 4,
                            f"peak memory grew by {growth / MIB:.1f} MiB while indexing a {size / MIB:.0f} MiB file")
            con = sqlite3.connect(os.path.join(tmp, "big.db"))
            self.assertEqual(con.execute("SELECT lines, nrows, cut FROM files").fetchone(), (1000, 1000, 1000))
            hit = con.execute("SELECT r.line FROM fts JOIN rows r ON r.id = fts.rowid WHERE fts MATCH 'chunkmarker999'")
            self.assertEqual(hit.fetchall(), [(1000,)])
            con.close()


